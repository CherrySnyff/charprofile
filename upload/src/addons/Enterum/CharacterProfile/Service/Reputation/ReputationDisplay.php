<?php

/**
 * Вкладка «Репутация» / UI: классы отношений и тексты подсказок фракций.
 * Статические хелперы по сумме репутации (despised…legend) без обращения к БД.
 */

namespace Enterum\CharacterProfile\Service\Reputation;

class ReputationDisplay
{
    /**
     * Репутация / UI: общая сумма из положительной и отрицательной частей.
     * $negative может быть отрицательным (−5) или абсолютным (5).
     *
     * subtractNegative=true  → положительная − |отрицательная|
     * subtractNegative=false → положительная + |отрицательная|
     */
    public static function computeTotal(int $positive, int $negative, ?bool $subtractNegative = null): int
    {
        if ($subtractNegative === null) {
            $subtractNegative = (bool)(\XF::options()->charProfileRepSubtractNegative ?? true);
        }

        $pos = abs($positive);
        $negAbs = abs($negative);

        return $subtractNegative ? ($pos - $negAbs) : ($pos + $negAbs);
    }

    /**
     * Репутация / UI: CSS-класс отношения по сумме (despised…legend).
     */
    public static function relationClass(int $sum): string
    {
        if ($sum <= -100) {
            return 'despised';
        }
        if ($sum >= -99 && $sum <= -70) {
            return 'hated';
        }
        if ($sum >= -69 && $sum <= -40) {
            return 'wanted';
        }
        if ($sum >= -39 && $sum <= -11) {
            return 'suspicious';
        }
        if ($sum >= -10 && $sum <= 10) {
            return 'neutral';
        }
        if ($sum >= 11 && $sum <= 39) {
            return 'friendly';
        }
        if ($sum >= 40 && $sum <= 69) {
            return 'promising';
        }
        if ($sum >= 70) {
            return $sum >= 100 ? 'legend' : 'hero';
        }

        return 'neutral';
    }

    /**
     * Репутация / UI: русская подпись отношения по сумме.
     */
    public static function relationLabel(int $sum): string
    {
        if ($sum <= -100) {
            return 'Презренный';
        }
        if ($sum >= -99 && $sum <= -70) {
            return 'Ненавистный';
        }
        if ($sum >= -69 && $sum <= -40) {
            return 'Разыскиваемый';
        }
        if ($sum >= -39 && $sum <= -11) {
            return 'Подозрительный';
        }
        if ($sum >= -10 && $sum <= 10) {
            return 'Нейтральный';
        }
        if ($sum >= 11 && $sum <= 39) {
            return 'Дружественный';
        }
        if ($sum >= 40 && $sum <= 69) {
            return 'Подающий надежды';
        }
        if ($sum >= 100) {
            return 'Легенда';
        }
        if ($sum >= 70) {
            return 'Герой';
        }

        return 'Нейтральный';
    }

